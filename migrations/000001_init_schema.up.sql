CREATE TABLE stock_alerts (
    id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    barang_id       BIGINT UNSIGNED NOT NULL,
    barang_masuk_id BIGINT UNSIGNED NULL,
    alert_type      ENUM('STOK_RENDAH','STOK_HABIS','MENDEKATI_EXP','KEDALUWARSA') NOT NULL,
    severity        ENUM('RENDAH','SEDANG','TINGGI','KRITIS') NOT NULL DEFAULT 'SEDANG',
    judul           VARCHAR(255) NOT NULL,
    pesan           TEXT NOT NULL,
    stok_saat_itu   INT NULL,
    nilai_ambang    INT NULL,
    tanggal_exp     DATE NULL,
    is_resolved     TINYINT(1) NOT NULL DEFAULT 0,
    resolved_at     DATETIME NULL,
    resolved_by     BIGINT UNSIGNED NULL,
    catatan_resolusi TEXT NULL,
    created_at      TIMESTAMP NULL,
    updated_at      TIMESTAMP NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_alert_terbuka (barang_id, barang_masuk_id, alert_type, is_resolved),
    KEY idx_alert_open (is_resolved, severity, created_at),
    CONSTRAINT fk_alert_barang FOREIGN KEY (barang_id) REFERENCES barang(id) ON DELETE CASCADE,
    CONSTRAINT fk_alert_bm FOREIGN KEY (barang_masuk_id) REFERENCES barang_masuk(id) ON DELETE CASCADE,
    CONSTRAINT fk_alert_user FOREIGN KEY (resolved_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

