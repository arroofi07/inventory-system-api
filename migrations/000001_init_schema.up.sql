CREATE TABLE riwayat_pembayaran (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaksi_penjualan_id BIGINT NOT NULL,
    old_jumlah_dibayar DECIMAL(15,2) NOT NULL DEFAULT 0,
    new_jumlah_dibayar DECIMAL(15,2) NOT NULL DEFAULT 0,
    old_sisa_hutang    DECIMAL(15,2) NOT NULL DEFAULT 0,
    new_sisa_hutang    DECIMAL(15,2) NOT NULL DEFAULT 0,
    old_status         VARCHAR(16) NULL,
    new_status         VARCHAR(16) NULL,
    nominal_pembayaran DECIMAL(15,2) NOT NULL DEFAULT 0,
    metode_pembayaran  VARCHAR(50) NULL,
    tanggal_pembayaran DATE NULL,
    keterangan         TEXT NULL,
    changed_by         BIGINT NULL,
    changed_at         TIMESTAMPTZ(3) NOT NULL,
    created_at         TIMESTAMPTZ NULL,
    CONSTRAINT fk_rp_transaksi FOREIGN KEY (transaksi_penjualan_id) REFERENCES transaksi_penjualan(id) ON DELETE CASCADE,
    CONSTRAINT fk_rp_user FOREIGN KEY (changed_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_rp_old_status CHECK (old_status IS NULL OR old_status IN ('lunas','hutang','sebagian')),
