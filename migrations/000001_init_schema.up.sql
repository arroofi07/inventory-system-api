CREATE TABLE users (
    id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name            VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    email_verified_at TIMESTAMP NULL,
    password        VARCHAR(255) NOT NULL,
    role            ENUM('super_admin','admin','afiliasi','sales') NOT NULL DEFAULT 'sales',
    no_hp           VARCHAR(30) NULL,
    no_ktp          VARCHAR(32) NULL,
    alamat          TEXT NULL,
    jenis_kelamin   ENUM('L','P') NULL,
    is_active       TINYINT(1) NOT NULL DEFAULT 1,
    created_at      TIMESTAMP NULL,
    updated_at      TIMESTAMP NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_users_email (email),
    UNIQUE KEY uq_users_no_ktp (no_ktp),
    KEY idx_users_role_active (role, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE refresh_tokens (
    id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id     BIGINT UNSIGNED NOT NULL,
    token_hash  CHAR(64) NOT NULL,
    expires_at  DATETIME NOT NULL,
    revoked_at  DATETIME NULL,
    user_agent  VARCHAR(255) NULL,
    ip_address  VARCHAR(45) NULL,
    created_at  TIMESTAMP NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_refresh_token_hash (token_hash),
    KEY idx_refresh_user_expired (user_id, expires_at),
    CONSTRAINT fk_refresh_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE barang (
    id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    kode_barang     VARCHAR(64) NOT NULL,
    nama_item       VARCHAR(255) NOT NULL,
    brand           VARCHAR(100) NOT NULL,
    satuan          VARCHAR(20) NOT NULL DEFAULT 'PCS',
    stok_tersedia   INT NOT NULL DEFAULT 0,
    min_stock       INT NOT NULL DEFAULT 0,
    reorder_point   INT NOT NULL DEFAULT 0,
    metode_alokasi  ENUM('FEFO','FIFO') NOT NULL DEFAULT 'FEFO',
    expiry_alert_days INT NOT NULL DEFAULT 30,
    is_active       TINYINT(1) NOT NULL DEFAULT 1,
    created_at      TIMESTAMP NULL,
    updated_at      TIMESTAMP NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_barang_kode (kode_barang),
    KEY idx_barang_brand (brand),
    KEY idx_barang_active_stok (is_active, stok_tersedia),
    KEY idx_barang_nama (nama_item)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

