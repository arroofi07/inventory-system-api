CREATE TABLE barang_masuk (
    id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    barang_id         BIGINT UNSIGNED NOT NULL,
    no_faktur         VARCHAR(100) NOT NULL,
    no_batch          VARCHAR(100) NOT NULL,
    exp               DATE NOT NULL,
    tanggal_masuk     DATE NOT NULL,
    qty               INT NOT NULL,
    harga             DECIMAL(15,2) NOT NULL,
    disc_hpp_1        DECIMAL(5,2) NOT NULL DEFAULT 0,
    disc_hpp_2        DECIMAL(5,2) NOT NULL DEFAULT 0,
    disc_hpp_3        DECIMAL(5,2) NOT NULL DEFAULT 0,
    hpp               DECIMAL(15,2) NOT NULL DEFAULT 0,
    hpp_dengan_ppn    DECIMAL(15,2) NOT NULL DEFAULT 0,
    markup_mt_type    ENUM('percent','value') NOT NULL DEFAULT 'percent',
    markup_mt_amount  DECIMAL(15,2) NOT NULL DEFAULT 0,
    markup_gt_type    ENUM('percent','value') NOT NULL DEFAULT 'percent',
    markup_gt_amount  DECIMAL(15,2) NOT NULL DEFAULT 0,
    harga_mt          DECIMAL(15,2) NOT NULL DEFAULT 0,
    harga_gt          DECIMAL(15,2) NOT NULL DEFAULT 0,
    aging_month       INT NOT NULL DEFAULT 0,
    created_by        BIGINT UNSIGNED NULL,
    created_at        TIMESTAMP NULL,
    updated_at        TIMESTAMP NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_bm_batch (barang_id, no_batch, no_faktur),
    KEY idx_bm_barang_exp (barang_id, exp),
    KEY idx_bm_tanggal (tanggal_masuk),
    KEY idx_bm_faktur (no_faktur),
    CONSTRAINT fk_bm_barang FOREIGN KEY (barang_id) REFERENCES barang(id) ON DELETE CASCADE,
    CONSTRAINT fk_bm_user FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_bm_qty CHECK (qty > 0),
    CONSTRAINT chk_bm_disc CHECK (
        disc_hpp_1 BETWEEN 0 AND 100 AND
        disc_hpp_2 BETWEEN 0 AND 100 AND
        disc_hpp_3 BETWEEN 0 AND 100
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE stock_movements (
    id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    barang_id         BIGINT UNSIGNED NOT NULL,
    barang_masuk_id   BIGINT UNSIGNED NULL,
    movement_type     ENUM('PENERIMAAN','PENJUALAN','PEMBATALAN','PENYESUAIAN','OPNAME') NOT NULL,
    qty               INT NOT NULL,
    saldo_setelah     INT NOT NULL,
    reference_type    VARCHAR(50) NULL,
    reference_id      BIGINT UNSIGNED NULL,
    reference_no      VARCHAR(100) NULL,
    keterangan        TEXT NULL,
    created_by        BIGINT UNSIGNED NULL,
    created_at        DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_sm_barang_created (barang_id, created_at),
    KEY idx_sm_batch (barang_masuk_id),
    KEY idx_sm_reference (reference_type, reference_id),
    KEY idx_sm_type_created (movement_type, created_at),
    CONSTRAINT fk_sm_barang FOREIGN KEY (barang_id) REFERENCES barang(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sm_batch FOREIGN KEY (barang_masuk_id) REFERENCES barang_masuk(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sm_user FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_sm_qty CHECK (qty <> 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE promos (
    id                  BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    kode_promo          VARCHAR(64) NOT NULL,
    nama_promo          VARCHAR(255) NOT NULL,
    deskripsi           TEXT NULL,
    tipe_promo          ENUM('buy_x_get_y','bonus_qty','percentage_discount','fixed_discount') NOT NULL,
    buy_qty             INT NULL,
    get_qty             INT NULL,
    bonus_qty           INT NOT NULL DEFAULT 0,
    discount_percentage DECIMAL(5,2) NOT NULL DEFAULT 0,
    discount_amount     DECIMAL(15,2) NOT NULL DEFAULT 0,
    min_qty             INT NOT NULL DEFAULT 1,
    min_amount          DECIMAL(15,2) NOT NULL DEFAULT 0,
    max_applications    INT NULL,
    kode_barang         VARCHAR(64) NULL,
    tanggal_mulai       DATE NOT NULL,
    tanggal_berakhir    DATE NOT NULL,
    is_active           TINYINT(1) NOT NULL DEFAULT 1,
    syarat_ketentuan    TEXT NULL,
    created_by          BIGINT UNSIGNED NULL,
    created_at          TIMESTAMP NULL,
    updated_at          TIMESTAMP NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_promo_kode (kode_promo),
    KEY idx_promo_aktif (is_active, tanggal_mulai, tanggal_berakhir),
    KEY idx_promo_barang (kode_barang),
    CONSTRAINT fk_promo_barang FOREIGN KEY (kode_barang) REFERENCES barang(kode_barang) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_promo_user FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_promo_periode CHECK (tanggal_berakhir >= tanggal_mulai),
    CONSTRAINT chk_promo_bxgy CHECK (
        tipe_promo <> 'buy_x_get_y'
        OR (buy_qty IS NOT NULL AND buy_qty > 0 AND get_qty IS NOT NULL AND get_qty > 0)
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE transaksi_penjualan (
    id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    no_transaksi      VARCHAR(32) NULL,
    tanggal           DATE NOT NULL,
    periode           CHAR(7) NOT NULL,
    kode_pelanggan    VARCHAR(32) NOT NULL,
    nama_pelanggan    VARCHAR(255) NOT NULL,
    alamat            TEXT NOT NULL,
    channel_outlet    VARCHAR(50) NOT NULL,
    area              VARCHAR(100) NOT NULL,
    is_multi_item     TINYINT(1) NOT NULL DEFAULT 1,
    disc1_persen      DECIMAL(5,2) NOT NULL DEFAULT 0,
    disc2_persen      DECIMAL(5,2) NOT NULL DEFAULT 0,
    disc3_persen      DECIMAL(5,2) NOT NULL DEFAULT 0,
    ppn_persen        DECIMAL(5,2) NOT NULL DEFAULT 11,
    total             DECIMAL(15,2) NOT NULL DEFAULT 0,
    ppn_nominal       DECIMAL(15,2) NOT NULL DEFAULT 0,
    total_akhir       DECIMAL(15,2) NOT NULL DEFAULT 0,
    jumlah_item       INT NOT NULL DEFAULT 0,
    total_qty_ditagih INT NOT NULL DEFAULT 0,
    total_qty_keluar  INT NOT NULL DEFAULT 0,
    status_approval   ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
    approved_at       DATETIME NULL,
    approved_by       BIGINT UNSIGNED NULL,
    approval_notes    TEXT NULL,
    fulfillment_status ENUM('awaiting_approval','full','partial','backorder','stock_shortage') NOT NULL DEFAULT 'awaiting_approval',
    qty_fulfilled     INT NOT NULL DEFAULT 0,
    qty_backorder     INT NOT NULL DEFAULT 0,
    stock_notes       TEXT NULL,
    status_pembayaran ENUM('lunas','hutang','sebagian') NOT NULL DEFAULT 'hutang',
    jumlah_dibayar    DECIMAL(15,2) NOT NULL DEFAULT 0,
    sisa_hutang       DECIMAL(15,2) NOT NULL DEFAULT 0,
    tanggal_jatuh_tempo DATE NULL,
    tanggal_pembayaran_terakhir DATETIME NULL,
    keterangan_pembayaran TEXT NULL,
    faktur_dicetak_at DATETIME NULL,
    faktur_dicetak_by BIGINT UNSIGNED NULL,
    sales_id          BIGINT UNSIGNED NULL,
    created_at        TIMESTAMP NULL,
    updated_at        TIMESTAMP NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_tp_no_transaksi (no_transaksi),
    KEY idx_tp_status_tanggal (status_approval, tanggal),
    KEY idx_tp_pelanggan (kode_pelanggan),
    KEY idx_tp_sales_tanggal (sales_id, tanggal),
    KEY idx_tp_bayar (status_pembayaran, tanggal_jatuh_tempo),
    KEY idx_tp_periode (periode),
    KEY idx_tp_channel (channel_outlet),
    CONSTRAINT fk_tp_pelanggan FOREIGN KEY (kode_pelanggan) REFERENCES pelanggan(kode_pelanggan) ON UPDATE CASCADE,
    CONSTRAINT fk_tp_sales FOREIGN KEY (sales_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_tp_approver FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_tp_bayar CHECK (
        ABS(jumlah_dibayar + sisa_hutang - total_akhir) < 0.01
    ),
    CONSTRAINT chk_tp_approved CHECK (
        (status_approval = 'approved' AND no_transaksi IS NOT NULL AND approved_at IS NOT NULL)
        OR status_approval <> 'approved'
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE transaksi_detail (
    id                    BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    transaksi_penjualan_id BIGINT UNSIGNED NOT NULL,
    urutan                SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    kode_item             VARCHAR(64) NOT NULL,
    nama_item             VARCHAR(255) NOT NULL,
    satuan                VARCHAR(20) NOT NULL,
    barang_masuk_id       BIGINT UNSIGNED NULL,
    batch_number          VARCHAR(100) NULL,
    expiry_date           DATE NULL,
    qty                   INT NOT NULL,
    qty_promo             INT NOT NULL DEFAULT 0,
    total_qty_keluar      INT NOT NULL DEFAULT 0,
    harga                 DECIMAL(15,2) NOT NULL,
    subtotal              DECIMAL(15,2) NOT NULL,
    disc1_persen          DECIMAL(5,2) NOT NULL DEFAULT 0,
    disc2_persen          DECIMAL(5,2) NOT NULL DEFAULT 0,
    disc3_persen          DECIMAL(5,2) NOT NULL DEFAULT 0,
    total_after_disc      DECIMAL(15,2) NOT NULL,
    hpp_snapshot          DECIMAL(15,2) NOT NULL DEFAULT 0,
    created_at            TIMESTAMP NULL,
    updated_at            TIMESTAMP NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_td_urutan (transaksi_penjualan_id, urutan),
    KEY idx_td_transaksi (transaksi_penjualan_id),
    KEY idx_td_item (kode_item),
    KEY idx_td_batch (barang_masuk_id),
    CONSTRAINT fk_td_transaksi FOREIGN KEY (transaksi_penjualan_id) REFERENCES transaksi_penjualan(id) ON DELETE CASCADE,
    CONSTRAINT fk_td_barang FOREIGN KEY (kode_item) REFERENCES barang(kode_barang) ON UPDATE CASCADE,
    CONSTRAINT fk_td_batch FOREIGN KEY (barang_masuk_id) REFERENCES barang_masuk(id) ON DELETE RESTRICT,
    CONSTRAINT chk_td_qty CHECK (qty > 0 AND qty_promo >= 0),
    CONSTRAINT chk_td_qty_keluar CHECK (total_qty_keluar = qty + qty_promo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

