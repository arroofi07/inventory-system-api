-- Skema domain PKB Web (PostgreSQL)

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    email_verified_at TIMESTAMPTZ NULL,
    password        VARCHAR(255) NOT NULL,
    role            VARCHAR(32) NOT NULL DEFAULT 'sales',
    no_hp           VARCHAR(30) NULL,
    no_ktp          VARCHAR(32) NULL,
    alamat          TEXT NULL,
    jenis_kelamin   VARCHAR(1) NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NULL,
    updated_at      TIMESTAMPTZ NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_no_ktp UNIQUE (no_ktp),
    CONSTRAINT chk_users_role CHECK (role IN ('super_admin','admin','afiliasi','sales')),
    CONSTRAINT chk_users_jk CHECK (jenis_kelamin IS NULL OR jenis_kelamin IN ('L','P'))
);
CREATE INDEX idx_users_role_active ON users (role, is_active);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    token_hash  CHAR(64) NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ NULL,
    user_agent  VARCHAR(255) NULL,
    ip_address  VARCHAR(45) NULL,
    created_at  TIMESTAMPTZ NULL,
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_refresh_user_expired ON refresh_tokens (user_id, expires_at);

CREATE TABLE barang (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_barang     VARCHAR(64) NOT NULL,
    nama_item       VARCHAR(255) NOT NULL,
    brand           VARCHAR(100) NOT NULL,
    satuan          VARCHAR(20) NOT NULL DEFAULT 'PCS',
    stok_tersedia   INT NOT NULL DEFAULT 0,
    min_stock       INT NOT NULL DEFAULT 0,
    reorder_point   INT NOT NULL DEFAULT 0,
    metode_alokasi  VARCHAR(8) NOT NULL DEFAULT 'FEFO',
    expiry_alert_days INT NOT NULL DEFAULT 30,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NULL,
    updated_at      TIMESTAMPTZ NULL,
    CONSTRAINT uq_barang_kode UNIQUE (kode_barang),
    CONSTRAINT chk_barang_metode CHECK (metode_alokasi IN ('FEFO','FIFO'))
);
CREATE INDEX idx_barang_brand ON barang (brand);
CREATE INDEX idx_barang_active_stok ON barang (is_active, stok_tersedia);
CREATE INDEX idx_barang_nama ON barang (nama_item);

CREATE TABLE pelanggan (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_pelanggan            VARCHAR(32) NOT NULL,
    nama_pelanggan            VARCHAR(255) NOT NULL,
    tgl_registrasi            DATE NOT NULL,
