    rt_rw                     VARCHAR(20) NULL,
    provinsi                  VARCHAR(100) NOT NULL,
    kabupaten                 VARCHAR(100) NOT NULL,
    kecamatan                 VARCHAR(100) NOT NULL,
    kelurahan                 VARCHAR(100) NOT NULL,
    kode_pos                  VARCHAR(10) NULL,
    channel_outlet            VARCHAR(40) NOT NULL,
    alamat_pengantaran_barang TEXT NULL,
    jenis_bangunan            VARCHAR(50) NULL,
    status_bangunan           VARCHAR(50) NULL,
    nominal_pengambilan_pertama DECIMAL(15,2) NOT NULL DEFAULT 0,
